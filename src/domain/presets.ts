// Helper to build standard Rx for different periodization models
export function buildRxForPeriodization(
  model: PeriodizationType,
  kind: 'compound' | 'isolation' | 'main'
): Record<Zone, Rx> {
  if (model === 'linear') {
    return {
      vol: {
        opts: kind === 'isolation' ? [[3, [10, 12]]] : [[3, 10]],
        rpe: [7.5, 8.5],
        cap: 0.7,
      },
      mid: {
        opts: kind === 'isolation' ? [[3, [8, 10]]] : [[4, 8]],
        rpe: [8, 9],
        cap: 0.8,
      },
      str: {
        opts: kind === 'isolation' ? [[3, [6, 8]]] : [[4, 6]],
        rpe: [8.5, 9.5],
        cap: 0.88,
      },
    };
  }

  if (model === 'block') {
    return {
      vol: {
        opts: kind === 'isolation' ? [[3, 12]] : [[4, 10]],
        rpe: [7, 8],
        cap: 0.68,
      },
      mid: {
        opts: kind === 'isolation' ? [[3, 8]] : [[4, 6]],
        rpe: [8, 9],
        cap: 0.82,
      },
      str: {
        opts: kind === 'isolation' ? [[3, 6]] : [[3, 4]],
        rpe: [9, 9.5],
        cap: 0.9,
      },
    };
  }

  if (model === 'fixed') {
    return {
      vol: {
        opts: kind === 'isolation' ? [[3, [10, 12]]] : [[3, [8, 10]]],
        rpe: [8, 9],
      },
      mid: {
        opts: kind === 'isolation' ? [[3, [10, 12]]] : [[3, [8, 10]]],
        rpe: [8, 9],
      },
      str: {
        opts: kind === 'isolation' ? [[3, [10, 12]]] : [[3, [8, 10]]],
        rpe: [8, 9],
      },
    };
  }

  // Default wave periodization
  return {
    vol: {
      opts: kind === 'isolation' ? [[3, [10, 12]]] : [[3, 10]],
      rpe: [7.5, 8.5],
      cap: 0.72,
    },
    mid: {
      opts: kind === 'isolation' ? [[3, [8, 10]]] : [[4, 8]],
      rpe: [8, 9],
      cap: 0.8,
    },
    str: {
      opts: kind === 'isolation' ? [[3, [6, 8]]] : [[4, 5]],
      rpe: [8.5, 9.5],
      cap: 0.88,
    },
  };
}

